const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'shared/legal-documents.json'), 'utf8');
const data = JSON.parse(source);
assert.match(data.version, /^\d{4}-\d{2}-\d{2}\.\d+$/);
const ids = ['privacy', 'terms', 'collection', 'sharing', 'permissions', 'children', 'rights'];
assert.deepEqual(data.documents.map(doc => doc.id), ids);
// WeChat registers JavaScript modules; JSON files are configuration, not require() modules.
const moduleSource = '// Generated by scripts/generate-legal.cjs. Edit shared/legal-documents.json instead.\nmodule.exports = ' + source.trimEnd() + ';\n';
const outputs = new Map([['miniprogram/utils/legal-documents.js', moduleSource]]);
for (const doc of data.documents) {
  assert.ok(doc.title && doc.summary && doc.sections.length, doc.id);
  const unique = new Set();
  const lines = ['# ' + doc.title, '', '版本：' + data.version + '；更新日期：' + data.updatedAt + '；生效日期：' + data.effectiveDate, '', doc.summary, ''];
  for (const section of doc.sections) {
    assert.ok(section.id && !unique.has(section.id), doc.id + ': section IDs must be unique');
    unique.add(section.id);
    lines.push('## ' + section.title, '', ...(section.paragraphs || []).flatMap(p => [p, '']));
    if (section.items) lines.push(...section.items.map(item => '- ' + item), '');
    if (section.table) {
      assert.ok(section.table.rows.every(row => row.length === section.table.columns.length), doc.id + ': table shape');
      const escape = value => String(value).replace(/\|/g, '\\|').replace(/\n/g, '<br>');
      lines.push('| ' + section.table.columns.map(escape).join(' | ') + ' |', '| ' + section.table.columns.map(() => '---').join(' | ') + ' |', ...section.table.rows.map(row => '| ' + row.map(escape).join(' | ') + ' |'), '');
    }
  }
  outputs.set('docs/legal/' + doc.id + '.md', lines.join('\n'));
}
const checking = process.argv.includes('--check');
const obsolete = path.join(root, 'miniprogram/utils/legal-documents.json');
if (fs.existsSync(obsolete)) {
  if (checking) {
    console.error('小程序仍有旧的 JSON 协议副本，请运行 npm run legal:generate');
    process.exitCode = 1;
  } else {
    fs.unlinkSync(obsolete);
  }
}
for (const [relative, content] of outputs) {
  const target = path.join(root, relative);
  if (checking) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
      console.error(relative + ' 与协议源不一致，请运行 npm run legal:generate');
      process.exitCode = 1;
    }
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
}
if (!process.exitCode) console.log('7 份协议、离线副本和表格结构' + (checking ? '校验通过。' : '已同步。'));
