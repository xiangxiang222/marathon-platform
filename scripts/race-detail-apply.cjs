#!/usr/bin/env node
// Build a reviewable update from a fixed authorized inventory, then apply that
// exact plan with a SQLite backup, optimistic row checks and per-race savepoints.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const Database = require('../server/node_modules/better-sqlite3');
const { readDetails, writeDetails } = require('../server/src/race-details');
const sha = value => crypto.createHash('sha256').update(value).digest('hex');
const compact = value => String(value || '').replace(/[\s\p{P}\p{S}]/gu, '');
const argsOf = argv => { const result = {}; for (let i=0;i<argv.length;i++) result[argv[i].replace(/^--/, '')] = argv[i+1] && !argv[i+1].startsWith('--') ? argv[++i] : true; return result; };
const read = file => JSON.parse(fs.readFileSync(file, 'utf8'));

const present = value => value !== undefined && value !== null && value !== '' && (!Array.isArray(value) || value.length > 0);
function mergeFacts(previous = {}, incoming = {}) {
  const result = structuredClone(previous);
  for (const [key, value] of Object.entries(incoming)) if (present(value)) result[key] = structuredClone(value);
  return result;
}
function feePhase(fee) { return compact(fee.label || fee.name || '普通价').replace(/普通价|标准价|常规价|报名费/g, '普通价'); }
function mergeGroups(previous = [], incoming = [], complete = false) {
  if (complete) return structuredClone(incoming);
  const result = structuredClone(previous);
  for (const group of incoming) {
    const index = result.findIndex(old => compact(old.name) === compact(group.name) || (old.sourceUrl && /\/(?:pkg|package)\/\d+/.test(old.sourceUrl) && old.sourceUrl === group.sourceUrl));
    if (index < 0) { result.push(structuredClone(group)); continue; }
    const old = result[index], merged = mergeFacts(old, group);
    if (old.fees?.length) {
      merged.fees = structuredClone(old.fees);
      for (const fee of group.fees || []) {
        const found = merged.fees.findIndex(saved => feePhase(saved) === feePhase(fee) && (!saved.unit || !fee.unit || saved.unit === fee.unit) && (!saved.startsAt || !fee.startsAt || saved.startsAt === fee.startsAt));
        if (found < 0) merged.fees.push(structuredClone(fee));
        else merged.fees[found] = mergeFacts(merged.fees[found], fee);
      }
    }
    result[index] = merged;
  }
  return result;
}

function reconcileGuide(previous, collected) {
  const old = readDetails(previous), details = structuredClone(collected.details);
  details.audit = { ...(old.details?.audit || {}), ...(details.audit || {}) };
  // A failed package page must not erase facts saved during an earlier visit.
  // Removing/renaming a group requires an explicit, checked official adjustment.
  details.groups = mergeGroups(old.details?.groups, details.groups, collected.verification?.groupsReconciledByOfficial === true);
  details.registration = mergeFacts(old.details?.registration, details.registration);
  if (old.details?.registration?.verified && (!details.registration?.verified || details.registration.status === 'unknown')) details.registration = old.details.registration;
  const previousMedia = old.details?.media || [];
  details.media = [...(details.media || [])];
  for (const image of previousMedia) if (!details.media.some(m => m.filename && m.filename === image.filename || m.url && m.url === image.url)) details.media.push(image);
  if (/^赛事已取消[。\s]/.test(old.text) && !collected.verification?.reinstatedByOfficial) {
    details.registration = { ...(details.registration || {}), status: 'cancelled', verified: true };
  }
  const freshText = collected.guideText || (details.sections || []).map(s => '## ' + s.title + '\n\n' + s.text).join('\n\n');
  // Missing/failed recognition is not a retraction. Keep the prior prose and
  // chapters when the new capture contains images or facts but no approved
  // replacement body. Never erase a reliable guide after an OCR failure.
  if (!String(freshText).trim() && old.text) {
    details.sections = old.details?.sections || [];
    details.audit.preservedExistingGuide = true;
    details.audit.missingApprovedReplacement = true;
    return { value: writeDetails(old.text, details), editorialPreserved: !!old.details?.audit?.preservedEditorialGuide || !old.details };
  }
  // Earlier generated summary fields are replaced by the full source. A long
  // human-edited guide is retained unless the new document contains its prose.
  const legacyHeading = /(?:\n\n|^)原有(?:规程|资料)|(?:\n\n|^)##?\s*原有/.exec(old.text);
  const legacy = legacyHeading ? old.text.slice(legacyHeading.index).replace(/^\s*(?:##?\s*)?原有(?:规程|资料)[：:\s]*/, '') : old.text;
  const autogenerated = /^(?:赛事已取消。|提示：|举办时间：|举办地点：|比赛项目：|分组：|赛事规模：)/.test(old.text) && old.text.length < 1200;
  const folded = compact(freshText);
  const paragraphs = legacy.split(/\n\s*\n/).filter(p => compact(p).length > 0);
  const editorial = old.details?.audit?.preservedEditorialGuide || !old.details;
  const retained = !collected.verification?.reconcilesExistingGuide && !autogenerated && old.text && editorial && paragraphs.some(p => !folded.includes(compact(p)));
  if (retained) {
    // Curated existing prose stays as the primary body; collected facts remain
    // structured, and the new complete document remains in the audit file.
    details.sections = [];
    details.audit = { ...(details.audit || {}), preservedEditorialGuide: true };
    return { value: writeDetails(old.text, details), editorialPreserved: true };
  }
  return { value: writeDetails(freshText, details), editorialPreserved: false };
}

function buildPlan(inventory, scope, directory) {
  const plans = [];
  for (const group of scope) {
    const ids = group.raceIds || [group.raceId];
    let collection;
    for (const id of ids) { const file = path.join(directory, id.replace(/[^\w.-]/g,'_') + '.json'); if (fs.existsSync(file)) { collection = read(file); break; } }
    const base = { key: group.key, name: group.name, raceIds: ids, synthetic: !!group.synthetic, sourceFile: collection ? path.join(directory, collection.id + '.json') : '', updates: [], failures: collection?.failures || [], coverage: collection?.coverage || null };
    if (group.synthetic) { plans.push({ ...base, state: 'demo_preserved' }); continue; }
    if (!collection?.details || !collection.coverage?.pages) { plans.push({ ...base, state: 'no_accessible_detail_preserved' }); continue; }
    for (const id of ids) {
      const previous = inventory.races.find(row => row.id === id);
      if (!previous) throw new Error('Out-of-scope race: ' + id);
      const draft = structuredClone(collection);
      const media = (draft.details.media || []).filter(m => m.localFile && fs.existsSync(m.localFile)).map(m => {
        const bytes = fs.readFileSync(m.localFile), fingerprint = sha(bytes), ext = bytes[0] === 0x89 ? '.png' : bytes.toString('ascii',0,4) === 'RIFF' ? '.webp' : '.jpg';
        return { ...m, filename: 'collected-' + fingerprint + ext, sha256: fingerprint, bytes: bytes.length };
      });
      draft.details.media = media;
      const reconciled = reconcileGuide(previous.guide_text, draft);
      const changes = { guide_text: reconciled.value, updated_at: new Date().toISOString().slice(0,10) };
      const savedDetails = readDetails(reconciled.value).details;
      if (savedDetails.groups?.length) changes.groups = savedDetails.groups.map(g => g.name).join(',');
      const reg = draft.details.registration;
      if (reg?.verified) {
        if (reg.opensAt && /^\d{4}-\d{2}-\d{2}/.test(reg.opensAt) && !previous.reg_start) changes.reg_start = reg.opensAt;
        if (reg.closesAt && /^\d{4}-\d{2}-\d{2}/.test(reg.closesAt) && !previous.deadline) { changes.deadline = reg.closesAt; changes.deadline_name = '报名截止'; }
        if (reg.url && /^https:\/\//.test(reg.url) && !previous.signup_url && reg.status !== 'cancelled' && reg.status !== 'invalid') changes.signup_url = reg.url;
      }
      for (const [key,value] of Object.entries(collection.fields || {})) if (['organizer','phone','route','pickup','fee','scale','start_at','reg_start','deadline'].includes(key) && value && !previous[key]) changes[key] = value;
      base.updates.push({ id, before: previous, changes, media, editorialPreserved: reconciled.editorialPreserved });
    }
    plans.push({ ...base, state: 'ready' });
  }
  return { version: 1, createdAt: new Date().toISOString(), authorizedIds: inventory.races.map(r => r.id), plans };
}

async function applyPlan(dbFile, plan, out, mediaRoot) {
  const db = new Database(dbFile), log = { startedAt: new Date().toISOString(), rows: [], backup: out + '.before.sqlite' };
  const schema = () => sha(JSON.stringify(db.prepare('SELECT type,name,tbl_name,sql FROM sqlite_master ORDER BY type,name').all()));
  const schemaBefore = schema();
  try {
    await db.backup(log.backup);
    const allowed = new Set(plan.authorizedIds);
    for (const entry of plan.plans) for (const update of entry.updates || []) {
      const record = { id: update.id, ok: false, copiedImages: 0, editorialPreserved: update.editorialPreserved };
      try {
        if (!allowed.has(update.id)) throw new Error('race_not_in_authorized_snapshot');
        const current = db.prepare('SELECT * FROM races WHERE id=?').get(update.id);
        if (!current || Object.keys(update.before).some(key => current[key] !== update.before[key])) throw new Error('race_changed_since_snapshot');
        const media = [];
        for (const image of update.media || []) {
          const bytes = fs.readFileSync(image.localFile);
          if (sha(bytes) !== image.sha256) throw new Error('media_hash_changed');
          const destination = path.join(mediaRoot, 'races', path.basename(image.filename));
          fs.mkdirSync(path.dirname(destination), { recursive: true });
          if (!fs.existsSync(destination)) { fs.writeFileSync(destination, bytes, { flag: 'wx' }); record.copiedImages++; }
          media.push(image);
        }
        db.transaction(() => {
          const details = readDetails(update.changes.guide_text);
          for (let i=0;i<media.length;i++) {
            const image = media[i];
            const previous = db.prepare('SELECT id FROM race_sheets WHERE race_id=? AND filename=?').get(update.id,image.filename);
            const sheetId = previous ? previous.id : Number(db.prepare('INSERT INTO race_sheets(race_id,kind,filename,sort,created_at) VALUES(?,?,?,?,?)').run(update.id,image.kind === 'route' ? 'route' : 'guide',image.filename,i,new Date().toISOString()).lastInsertRowid);
            const saved = details.details.media.find(m => m.filename === image.filename); if (saved) saved.sheetId = sheetId;
          }
          const changes = { ...update.changes, guide_text: writeDetails(details.text,details.details) };
          const allowedFields = new Set(['guide_text','updated_at','groups','organizer','phone','place','route','pickup','fee','scale','start_at','reg_start','deadline','deadline_name','signup_url']);
          if (Object.keys(changes).some(key => !allowedFields.has(key))) throw new Error('unsupported_update_field');
          db.prepare('UPDATE races SET ' + Object.keys(changes).map(key => key+'=?').join(',') + ' WHERE id=?').run(...Object.values(changes),update.id);
          record.savedHash = sha(changes.guide_text); record.groupCount = details.details.groups?.length || 0; record.sheetCount = media.length;
        })();
        record.ok = true;
      } catch (error) { record.error = error.message; }
      log.rows.push(record);
      fs.writeFileSync(out,JSON.stringify(log,null,2));
    }
    log.schemaUnchanged = schemaBefore === schema(); log.quickCheck = db.pragma('quick_check', { simple: true });
    log.completedAt = new Date().toISOString(); fs.writeFileSync(out,JSON.stringify(log,null,2)); return log;
  } finally { db.close(); }
}

if (require.main === module) (async () => {
  const args = argsOf(process.argv.slice(2));
  if (args.apply) {
    if (!args.db || !args.plan || !args.out || !args.media) throw new Error('--apply requires --db --plan --out --media');
    const log = await applyPlan(args.db,read(args.plan),args.out,args.media);
    console.log(JSON.stringify({ saved:log.rows.filter(r=>r.ok).length,failed:log.rows.filter(r=>!r.ok).length,schemaUnchanged:log.schemaUnchanged,quickCheck:log.quickCheck,backup:log.backup }));
    if (log.rows.some(r=>!r.ok)) process.exitCode=1;
  } else {
    const plan = buildPlan(read(args.inventory),read(args.scope),args.collections); fs.writeFileSync(args.out,JSON.stringify(plan,null,2));
    console.log(JSON.stringify({ groups:plan.plans.length,ready:plan.plans.filter(p=>p.state==='ready').length,rows:plan.plans.reduce((n,p)=>n+p.updates.length,0),out:args.out }));
  }
})().catch(error=>{console.error(error.message);process.exitCode=1;});
module.exports = { buildPlan, applyPlan, reconcileGuide };
